export function hybridTasks(tasks, random = Math.random) {
  const deck = [...CONCEPTS];
  for (let i = deck.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [deck[i], deck[j]] = [deck[j], deck[i]];
  }
  return tasks.map((task, i) => {
    const chosen = deck[i],
      roles = [
        ...new Set(
          (task.parts || task.regions).flatMap((r) =>
            taskRoles(r.sourceLabel || r.label),
          ),
        ),
      ];
    return {
      ...task,
      concept: { id: chosen.id, title: chosen.title },
      roles,
      briefs: roles.map((role) => ({
        role,
        label: ROLE_LABELS[role],
        text: chosen[role],
      })),
    };
  });
}
