function remix([baseId, name, head, body], i) {
  const base = structuredClone(BUILTIN_SCHEMAS.find((s) => s.id === baseId));
  base.id = `character-${i + 1}`;
  base.name = name;
  base.keywords = [name.toLocaleLowerCase("ru")];
  for (const layout of [base, ...Object.values(base.layouts || {})])
    for (const region of layout.regions) {
      region.instruction +=
        " " + (/голов|лицо|купол|шляпк/i.test(region.label) ? head : body);
    }
  return base;
}
BUILTIN_SCHEMAS.push(...CHARACTERS.map(remix));
