// Schemes are geometry and instructions, not pictures: they never reveal a reference image.
const block = (label, x, y, w, h, instruction = "") => ({
  label,
  x,
  y,
  w,
  h,
  instruction,
});
const horizontal = (cut, label = "Шея", from = 0.4, to = 0.6) =>
  [from, to].map((x) => ({ x, y: cut, label, group: `h-${cut}` }));
const vertical = (cut, label = "Туловище", from = 0.35, to = 0.65) =>
  [from, to].map((y) => ({ x: cut, y, label, group: `v-${cut}` }));
function stack(labels, cuts, joins = []) {
  const positions = [0, ...cuts, 1];
  return {
    regions: labels.map((label, i) =>
      block(
        label,
        0,
        positions[i],
        1,
        positions[i + 1] - positions[i],
        i === 0
          ? "Нарисуй верхнюю часть. Нижние линии должны прийти к цветному стыку."
          : i === labels.length - 1
            ? "Продолжи контур от стыка сверху. Нижнюю часть придумай сам."
            : "Соедини верхний и нижний стыки. Не меняй положение цветных меток.",
      ),
    ),
    anchors: cuts.flatMap((cut, i) =>
      horizontal(cut, joins[i] || "Продолжение"),
    ),
  };
}
function side(labels, cuts, joins = []) {
  const positions = [0, ...cuts, 1];
  return {
    regions: labels.map((label, i) =>
      block(
        label,
        positions[i],
        0,
        positions[i + 1] - positions[i],
        1,
        i === 0
          ? "Передняя часть смотрит влево. Продолжи контур к стыку справа."
          : i === labels.length - 1
            ? "Начни у стыка слева. Задняя часть направлена вправо."
            : "Соедини стыки слева и справа. Верх — спина, низ — живот.",
      ),
    ),
    anchors: cuts.flatMap((cut, i) => vertical(cut, joins[i] || "Продолжение")),
  };
}
function preset(id, name, keywords, layout, duo, trio) {
  return {
    version: 1,
    id,
    name,
    keywords,
    ...layout,
    layouts: { 2: duo, ...(trio ? { 3: trio } : {}) },
  };
}
